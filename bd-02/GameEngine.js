export class Palette {
  #data;

  /**
   * @param {Uint8Array} [data=DEFAULT_PALETTE_PIXELS] - Flat RGB byte array (3 bytes per color).
   */
  constructor(data = DEFAULT_PALETTE_PIXELS) {
    this.setData(data);
  }

  get data() {
    return this.#data;
  }

  get count() {
    return Math.floor(this.#data.length / 3);
  }

  /**
   * Replaces the underlying flat RGB byte array.
   * @param {Uint8Array} data
   */
  setData(data) {
    if (!(data instanceof Uint8Array)) {
      throw new TypeError("Palette data must be a Uint8Array");
    }
    this.#data = data;
    return this;
  }

  /**
   * Retrieves an RGB color object by zero-based color index.
   * @param {number} index
   * @returns {{ r: number, g: number, b: number }}
   */
  getColor(index) {
    const maxIndex = this.count - 1;
    if (!Number.isInteger(index) || index < 0 || index > maxIndex) {
      throw new RangeError(`Palette index ${index} out of bounds (0..${maxIndex})`);
    }

    const offset = index * 3;
    return {
      r: this.#data[offset],
      g: this.#data[offset + 1],
      b: this.#data[offset + 2],
    };
  }

  /**
   * Retrieves a `#rrggbb` hex color string by zero-based color index.
   * @param {number} index
   * @returns {string}
   */
  getHexColor(index) {
    const { r, g, b } = this.getColor(index);
    const toHex = (n) => n.toString(16).padStart(2, "0");
    return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
  }
}

export class Graphics {
  #canvas = null;
  #ctx = null;
  #buffer = null;
  #bufferCtx = null;
  #scale = 1;
  #palette;
  #font;

  /**
   * @param {HTMLCanvasElement} [canvas] - Optional visible canvas to attach immediately.
   * @param {Palette} [palette=new Palette()] - Palette instance used to resolve color indices.
   * @param {Object} [fontData=DEFAULT_FONT] - Bitmap font definition.
   */
  constructor(canvas = null, palette = new Palette(), fontData = DEFAULT_FONT) {
    this.palette = palette;
    this.font = fontData;
    if (canvas) {
      this.init(canvas);
    }
  }

  /**
   * Initializes the visible canvas and creates a matching off-screen back buffer.
   * @param {HTMLCanvasElement} targetCanvas
   */
  init(targetCanvas) {
    this.#canvas = targetCanvas;
    this.#ctx = targetCanvas.getContext("2d", { alpha: false });
    this.#ctx.imageSmoothingEnabled = false;

    this.#buffer = document.createElement("canvas");
    this.#bufferCtx = this.#buffer.getContext("2d", { alpha: false });
    this.#bufferCtx.imageSmoothingEnabled = false;

    this.syncSize();
    return this;
  }

  /**
   * Ensures the back buffer matches the visible canvas dimensions.
   */
  syncSize() {
    if (!this.#canvas || !this.#buffer) return;
    if (
      this.#buffer.width !== this.#canvas.width ||
      this.#buffer.height !== this.#canvas.height
    ) {
      this.#buffer.width = this.#canvas.width;
      this.#buffer.height = this.#canvas.height;
      this.#bufferCtx.imageSmoothingEnabled = false;
      this.#ctx.imageSmoothingEnabled = false;
    }
  }

  /**
   * Copies the completed back buffer to the visible screen canvas.
   */
  flip() {
    if (!this.#ctx || !this.#buffer) return;
    this.syncSize();
    this.#ctx.drawImage(this.#buffer, 0, 0);
  }

  get canvas() {
    return this.#canvas;
  }

  get ctx() {
    return this.#bufferCtx;
  }

  get frontCtx() {
    return this.#ctx;
  }

  get scale() {
    return this.#scale;
  }

  set scale(value) {
    if (typeof value !== "number" || !Number.isFinite(value) || value <= 0) {
      throw new RangeError("Scale must be a positive finite number");
    }

    this.#scale = value;
    if (this.#canvas && this.#ctx) {
      this.syncSize();
      this.#canvas.style.width = `${this.#canvas.width * value}px`;
      this.#canvas.style.height = `${this.#canvas.height * value}px`;
      this.#canvas.style.imageRendering = "pixelated";
      this.#ctx.imageSmoothingEnabled = false;
    }
  }

  get palette() {
    return this.#palette;
  }

  set palette(value) {
    if (!(value instanceof Palette)) {
      throw new TypeError("Palette must be an instance of Palette");
    }
    this.#palette = value;
  }

  get font() {
    return this.#font;
  }

  set font(value) {
    if (!value || !(value.pixels instanceof Uint8Array)) {
      throw new TypeError("Font must define a Uint8Array `pixels` property");
    }
    this.#font = value;
  }

  _resolveColor(c) {
    return typeof c === "number" ? this.#palette.getHexColor(c) : c;
  }

  dchar(char, x, y, c) {
    const code = typeof char === "number" ? char : char.charCodeAt(0);
    const glyphIndex = ((code % this.#font.frames) + this.#font.frames) % this.#font.frames;
    const baseOffset = glyphIndex * this.#font.height;
    const px = Math.floor(x);
    const py = Math.floor(y);

    this.#bufferCtx.fillStyle = this._resolveColor(c);

    for (let row = 0; row < this.#font.height; row++) {
      const bits = this.#font.pixels[baseOffset + row];
      if (bits === 0) continue;

      for (let col = 0; col < this.#font.width; col++) {
        if ((bits & (0x80 >>> col)) !== 0) {
          this.#bufferCtx.fillRect(px + col, py + row, 1, 1);
        }
      }
    }
  }

  dtext(text, x, y, c) {
    const str = String(text);
    let cursorX = x;
    let cursorY = y;

    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === "\n") {
        cursorX = x;
        cursorY += this.#font.height;
        continue;
      }

      this.dchar(ch, cursorX, cursorY, c);
      cursorX += this.#font.width;
    }
  }

  cls(c = 0) {
    this.syncSize();
    this.#bufferCtx.fillStyle = this._resolveColor(c);
    this.#bufferCtx.fillRect(0, 0, this.#buffer.width, this.#buffer.height);
  }

  pset(x, y, c) {
    const px = Math.floor(x);
    const py = Math.floor(y);
    this.#bufferCtx.fillStyle = this._resolveColor(c);
    this.#bufferCtx.fillRect(px, py, 1, 1);
  }

  pget(x, y) {
    const px = Math.floor(x);
    const py = Math.floor(y);
    const data = this.#bufferCtx.getImageData(px, py, 1, 1).data;
    const toHex = (n) => n.toString(16).padStart(2, "0");
    return `#${toHex(data[0])}${toHex(data[1])}${toHex(data[2])}`;
  }

  dline(x0, y0, x1, y1, c) {
    x0 = Math.round(x0);
    y0 = Math.round(y0);
    x1 = Math.round(x1);
    y1 = Math.round(y1);

    const dx = Math.abs(x1 - x0);
    const dy = Math.abs(y1 - y0);
    const sx = x0 < x1 ? 1 : -1;
    const sy = y0 < y1 ? 1 : -1;
    let err = dx - dy;

    while (true) {
      this.pset(x0, y0, c);
      if (x0 === x1 && y0 === y1) break;
      const e2 = 2 * err;
      if (e2 > -dy) {
        err -= dy;
        x0 += sx;
      }
      if (e2 < dx) {
        err += dx;
        y0 += sy;
      }
    }
  }

  drect(x, y, w, h, c) {
    x = Math.round(x);
    y = Math.round(y);
    w = Math.round(w);
    h = Math.round(h);
    if (w <= 0 || h <= 0) return;

    const x2 = x + w - 1;
    const y2 = y + h - 1;

    for (let ix = x; ix <= x2; ix++) {
      this.pset(ix, y, c);
      this.pset(ix, y2, c);
    }
    for (let iy = y + 1; iy < y2; iy++) {
      this.pset(x, iy, c);
      this.pset(x2, iy, c);
    }
  }

  frect(x, y, w, h, c) {
    x = Math.round(x);
    y = Math.round(y);
    w = Math.round(w);
    h = Math.round(h);
    if (w <= 0 || h <= 0) return;

    for (let iy = y; iy < y + h; iy++) {
      for (let ix = x; ix < x + w; ix++) {
        this.pset(ix, iy, c);
      }
    }
  }

  dcirc(cx, cy, r, c) {
    cx = Math.round(cx);
    cy = Math.round(cy);
    r = Math.round(r);
    if (r < 0) return;

    if (r === 0) {
      this.pset(cx, cy, c);
      return;
    }

    let x = 0;
    let y = r;
    let err = 1 - r;

    const plot8 = (px, py) => {
      this.pset(cx + px, cy + py, c);
      this.pset(cx - px, cy + py, c);
      this.pset(cx + px, cy - py, c);
      this.pset(cx - px, cy - py, c);
      if (px !== py) {
        this.pset(cx + py, cy + px, c);
        this.pset(cx - py, cy + px, c);
        this.pset(cx + py, cy - px, c);
        this.pset(cx - py, cy - px, c);
      }
    };

    while (x <= y) {
      plot8(x, y);
      x++;
      if (err < 0) {
        err += 2 * x + 1;
      } else {
        y--;
        err += 2 * (x - y) + 1;
      }
    }
  }

  fcirc(cx, cy, r, c) {
    cx = Math.round(cx);
    cy = Math.round(cy);
    r = Math.round(r);
    if (r < 0) return;

    if (r === 0) {
      this.pset(cx, cy, c);
      return;
    }

    this.#bufferCtx.fillStyle = this._resolveColor(c);

    let x = 0;
    let y = r;
    let err = 1 - r;

    const maxSpanX = new Int32Array(r + 1);

    while (x <= y) {
      if (y > maxSpanX[x]) maxSpanX[x] = y;
      if (x > maxSpanX[y]) maxSpanX[y] = x;

      x++;
      if (err < 0) {
        err += 2 * x + 1;
      } else {
        y--;
        err += 2 * (x - y) + 1;
      }
    }

    for (let dy = 0; dy <= r; dy++) {
      const span = maxSpanX[dy];
      const left = cx - span;
      const width = span * 2 + 1;

      this.#bufferCtx.fillRect(left, cy + dy, width, 1);
      if (dy !== 0) {
        this.#bufferCtx.fillRect(left, cy - dy, width, 1);
      }
    }
  }
}

export class Pointer {
  /**
   * @param {HTMLCanvasElement} canvas
   * @param {Object} [options]
   * @param {boolean} [options.hideCursor=false]
   * @param {boolean} [options.preventContextMenu=false]
   */
  constructor(canvas, options = {}) {
    if (!canvas) {
      throw new Error("Pointer requires a target HTMLCanvasElement.");
    }

    this.canvas = canvas;
    this.hideCursor = Boolean(options.hideCursor);
    this.preventContextMenu = Boolean(options.preventContextMenu);

    // Logical canvas coordinates
    this.x = 0;
    this.y = 0;
    this.prevX = 0;
    this.prevY = 0;
    this.dx = 0;
    this.dy = 0;

    // Frame-level button states (keyed by MouseEvent.button: 0=left, 1=middle, 2=right)
    this._currentDown = new Set();
    this._previousDown = new Set();
    this._pressedThisFrame = new Set();
    this._releasedThisFrame = new Set();
    this._hasMoved = false;

    this._onPointerMove = this._handlePointerMove.bind(this);
    this._onPointerDown = this._handlePointerDown.bind(this);
    this._onPointerUp = this._handlePointerUp.bind(this);
    this._onPointerLeave = this._handlePointerLeave.bind(this);
    this._onContextMenu = this._handleContextMenu.bind(this);

    this._attachEvents();
    this._applyOptions();
  }

  _attachEvents() {
    this.canvas.addEventListener("pointermove", this._onPointerMove);
    this.canvas.addEventListener("pointerdown", this._onPointerDown);
    window.addEventListener("pointerup", this._onPointerUp);
    this.canvas.addEventListener("pointerleave", this._onPointerLeave);

    if (this.preventContextMenu) {
      this.canvas.addEventListener("contextmenu", this._onContextMenu);
    }
  }

  _applyOptions() {
    if (this.hideCursor) {
      this.canvas.style.cursor = "none";
    }
  }

  _updatePositionFromEvent(event) {
    const rect = this.canvas.getBoundingClientRect();
    if (rect.width === 0 || rect.height === 0) return;

    const scaleX = this.canvas.width / rect.width;
    const scaleY = this.canvas.height / rect.height;

    this.x = Math.floor((event.clientX - rect.left) * scaleX);
    this.y = Math.floor((event.clientY - rect.top) * scaleY);

    if (!this._hasMoved) {
      this.prevX = this.x;
      this.prevY = this.y;
      this._hasMoved = true;
    }
  }

  _handlePointerMove(event) {
    this._updatePositionFromEvent(event);
  }

  _handlePointerDown(event) {
    this._updatePositionFromEvent(event);
    if (!this._currentDown.has(event.button)) {
      this._pressedThisFrame.add(event.button);
    }
    this._currentDown.add(event.button);
  }

  _handlePointerUp(event) {
    if (this._currentDown.has(event.button)) {
      this._releasedThisFrame.add(event.button);
    }
    this._currentDown.delete(event.button);
  }

  _handlePointerLeave() {
    for (const btn of this._currentDown) {
      this._releasedThisFrame.add(btn);
    }
    this._currentDown.clear();
  }

  _handleContextMenu(event) {
    event.preventDefault();
  }

  /**
   * Advances per-frame input state (deltas and just-pressed / just-released edges).
   * Call once per frame at the end of your game loop.
   */
  update() {
    this.dx = this.x - this.prevX;
    this.dy = this.y - this.prevY;
    this.prevX = this.x;
    this.prevY = this.y;

    this._previousDown = new Set(this._currentDown);
    this._pressedThisFrame.clear();
    this._releasedThisFrame.clear();
  }

  /**
   * Returns true while the given mouse button is held down.
   * @param {number} [button=0]
   */
  isDown(button = 0) {
    return this._currentDown.has(button);
  }

  /**
   * Returns true only on the frame the button transitioned from up to down.
   * @param {number} [button=0]
   */
  isPressed(button = 0) {
    return (
      this._pressedThisFrame.has(button) ||
      (this._currentDown.has(button) && !this._previousDown.has(button))
    );
  }

  /**
   * Returns true only on the frame the button transitioned from down to up.
   * @param {number} [button=0]
   */
  isReleased(button = 0) {
    return (
      this._releasedThisFrame.has(button) ||
      (!this._currentDown.has(button) && this._previousDown.has(button))
    );
  }

  /**
   * Removes event listeners and restores default cursor style if modified.
   */
  destroy() {
    this.canvas.removeEventListener("pointermove", this._onPointerMove);
    this.canvas.removeEventListener("pointerdown", this._onPointerDown);
    window.removeEventListener("pointerup", this._onPointerUp);
    this.canvas.removeEventListener("pointerleave", this._onPointerLeave);
    this.canvas.removeEventListener("contextmenu", this._onContextMenu);

    if (this.hideCursor) {
      this.canvas.style.cursor = "";
    }
  }
}

export class Keyboard {
  /**
   * @param {Object} [options]
   * @param {EventTarget} [options.target=window] - Event target to attach listeners to.
   * @param {boolean} [options.preventDefault=false] - Prevent default browser actions for tracked/all keys.
   * @param {Set<string>|Array<string>} [options.preventDefaultKeys] - Specific KeyboardEvent.code values to prevent default on (when preventDefault is true, prevents all).
   */
  constructor(options = {}) {
    this.target = options.target ?? window;
    this.preventDefault = Boolean(options.preventDefault);
    this.preventDefaultKeys = options.preventDefaultKeys
      ? new Set(options.preventDefaultKeys)
      : null;

    // Frame-level key states keyed by KeyboardEvent.code (e.g. "ArrowUp", "KeyW", "Space")
    this._currentDown = new Set();
    this._previousDown = new Set();
    this._pressedThisFrame = new Set();
    this._releasedThisFrame = new Set();

    // Optional typed character buffer for text entry (cleared on update or read/flush)
    this._typedChars = [];

    this._onKeyDown = this._handleKeyDown.bind(this);
    this._onKeyUp = this._handleKeyUp.bind(this);
    this._onBlur = this._handleBlur.bind(this);

    this._attachEvents();
  }

  _attachEvents() {
    this.target.addEventListener("keydown", this._onKeyDown);
    this.target.addEventListener("keyup", this._onKeyUp);
    window.addEventListener("blur", this._onBlur);
  }

  _shouldPreventDefault(event) {
    if (!this.preventDefault) return false;
    if (!this.preventDefaultKeys) return true;
    return this.preventDefaultKeys.has(event.code);
  }

  _handleKeyDown(event) {
    if (this._shouldPreventDefault(event)) {
      event.preventDefault();
    }

    if (
      event.key.length === 1 &&
      !event.ctrlKey &&
      !event.metaKey &&
      !event.altKey
    ) {
      this._typedChars.push(event.key);
    }

    if (!this._currentDown.has(event.code)) {
      this._pressedThisFrame.add(event.code);
    }
    this._currentDown.add(event.code);
  }

  _handleKeyUp(event) {
    if (this._currentDown.has(event.code)) {
      this._releasedThisFrame.add(event.code);
    }
    this._currentDown.delete(event.code);
  }

  _handleBlur() {
    for (const code of this._currentDown) {
      this._releasedThisFrame.add(code);
    }
    this._currentDown.clear();
  }

  /**
   * Advances per-frame input state for edge detection (isPressed / isReleased).
   * Call once per frame at the end of your game loop.
   */
  update() {
    this._previousDown = new Set(this._currentDown);
    this._pressedThisFrame.clear();
    this._releasedThisFrame.clear();
    this._typedChars.length = 0;
  }

  /**
   * Returns true while the given key code is held down.
   * @param {string} code - KeyboardEvent.code (e.g. "ArrowLeft", "KeyA", "Space").
   */
  isDown(code) {
    return this._currentDown.has(code);
  }

  /**
   * Returns true only on the frame the key transitioned from up to down.
   * @param {string} code
   */
  isPressed(code) {
    return (
      this._pressedThisFrame.has(code) ||
      (this._currentDown.has(code) && !this._previousDown.has(code))
    );
  }

  /**
   * Returns true only on the frame the key transitioned from down to up.
   * @param {string} code
   */
  isReleased(code) {
    return (
      this._releasedThisFrame.has(code) ||
      (!this._currentDown.has(code) && this._previousDown.has(code))
    );
  }

  /**
   * Returns a string of printable characters typed during the current frame.
   * @returns {string}
   */
  getTypedText() {
    return this._typedChars.join("");
  }

  /**
   * Clears all currently held keys.
   */
  clear() {
    this._currentDown.clear();
    this._previousDown.clear();
    this._pressedThisFrame.clear();
    this._releasedThisFrame.clear();
    this._typedChars.length = 0;
  }

  /**
   * Removes all event listeners and resets state.
   */
  destroy() {
    this.target.removeEventListener("keydown", this._onKeyDown);
    this.target.removeEventListener("keyup", this._onKeyUp);
    window.removeEventListener("blur", this._onBlur);
    this.clear();
  }
}

export class GameEngine {
  /**
   * @param {Object} [options]
   * @param {string|HTMLCanvasElement} [options.canvas="canvas"] - Target canvas element or DOM ID.
   * @param {number} [options.width=320] - Logical back-buffer width.
   * @param {number} [options.height=200] - Logical back-buffer height.
   * @param {number} [options.scale=2] - Display pixel scale factor.
   * @param {Uint8Array|Palette} [options.palette] - Custom Uint8Array or Palette instance.
   * @param {Object} [options.font] - Custom bitmap font definition.
   * @param {Object} [options.pointer] - Options forwarded to Pointer.
   * @param {Object} [options.keyboard] - Options forwarded to Keyboard.
   * @param {number} [options.maxDelta=0.1] - Maximum frame delta time in seconds.
   * @param {Function} [options.setup] - Optional setup hook called on start().
   * @param {Function} [options.update] - Optional update(dt, engine) hook called every active frame.
   * @param {Function} [options.draw] - Optional draw(engine) hook called every frame.
   */
  constructor(options = {}) {
    const canvasTarget = options.canvas ?? "canvas";
    this.canvas =
      typeof canvasTarget === "string"
        ? document.getElementById(canvasTarget)
        : canvasTarget;

    if (!this.canvas) {
      throw new Error(`GameEngine could not find canvas "${canvasTarget}".`);
    }

    this.width = options.width ?? 320;
    this.height = options.height ?? 200;
    this.initialScale = options.scale ?? 2;
    this.maxDelta = options.maxDelta ?? 0.1;

    if (options.palette instanceof Palette) {
      this.palette = options.palette;
    } else if (options.palette instanceof Uint8Array) {
      this.palette = new Palette(options.palette);
    } else {
      this.palette = new Palette(DEFAULT_PALETTE_PIXELS);
    }

    this.font = options.font ?? DEFAULT_FONT;
    this.gfx = new Graphics(this.canvas, this.palette, this.font);

    this.pointer = new Pointer(this.canvas, {
      preventContextMenu: true,
      hideCursor: true,
      ...options.pointer,
    });

    this.keyboard = new Keyboard({
      preventDefault: true,
      preventDefaultKeys: [
        "ArrowUp",
        "ArrowDown",
        "ArrowLeft",
        "ArrowRight",
        "Space",
      ],
      ...options.keyboard,
    });

    this._setupHook = options.setup ?? null;
    this._updateHook = options.update ?? null;
    this._drawHook = options.draw ?? null;

    this.paused = false;
    this.running = false;
    this.elapsed = 0;
    this.lastTime = performance.now();
    this._rafId = null;
    this._onFrame = this._loop.bind(this);
  }

  get pal() {
    return this.palette;
  }

  setPalette(nextPalette) {
    const instance =
      nextPalette instanceof Palette
        ? nextPalette
        : nextPalette instanceof Uint8Array
          ? new Palette(nextPalette)
          : null;

    if (!instance) {
      throw new TypeError("Palette must be a Palette instance or Uint8Array.");
    }

    this.palette = instance;
    this.gfx.palette = instance;
    return this;
  }

  setFont(nextFont) {
    this.font = nextFont;
    this.gfx.font = nextFont;
    return this;
  }

  setup() {
    this.canvas.width = this.width;
    this.canvas.height = this.height;
    this.gfx.syncSize();
    this.gfx.scale = this.initialScale;
    this.gfx.cls(0);
    this.gfx.flip();

    this.paused = false;
    this.elapsed = 0;
    this.lastTime = performance.now();

    if (typeof this._setupHook === "function") {
      this._setupHook(this);
    }
  }

  update(_dt) {}

  draw() {}

  _loop(now = performance.now()) {
    if (!this.running) return;

    const dt = Math.min(Math.max((now - this.lastTime) / 1000, 0), this.maxDelta);
    this.lastTime = now;

    if (!this.paused) {
      this.elapsed += dt;
      this.update(dt);
      if (typeof this._updateHook === "function") {
        this._updateHook(dt, this);
      }
    }

    this.draw();
    if (typeof this._drawHook === "function") {
      this._drawHook(this);
    }

    this.gfx.flip();

    this.pointer.update();
    this.keyboard.update();

    this._rafId = requestAnimationFrame(this._onFrame);
  }

  pause(state = true) {
    this.paused = Boolean(state);
    this.lastTime = performance.now();
  }

  resume() {
    this.pause(false);
  }

  togglePause() {
    this.pause(!this.paused);
  }

  start() {
    this.stop();
    this.running = true;
    this.setup();
    this._rafId = requestAnimationFrame(this._onFrame);
  }

  stop() {
    this.running = false;
    if (this._rafId !== null) {
      cancelAnimationFrame(this._rafId);
      this._rafId = null;
    }
  }

  destroy() {
    this.stop();
    this.pointer.destroy();
    this.keyboard.destroy();
  }
}
